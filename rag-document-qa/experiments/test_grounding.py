from app.evaluation.grounding import evaluate_claim


context = """
Retrieval-Augmented Generation combines information retrieval
with language-model generation. During retrieval, relevant
information is selected from a document collection and provided
to the language model as context.
"""


tests = [
    {
        "claim": (
            "RAG combines information retrieval "
            "with language-model generation."
        )
    },
    {
        "claim": (
            "RAG provides retrieved information "
            "to the language model."
        )
    },
    {
        "claim": (
            "RAG guarantees that every answer "
            "generated by the language model is correct."
        )
    }
]


print("\n" + "=" * 70)
print("SEMANTIC GROUNDING TEST")
print("=" * 70)


for index, test in enumerate(
    tests,
    start=1
):
    claim = test["claim"]

    result = evaluate_claim(
        claim,
        context
    )

    print("\n" + "-" * 70)

    print("Claim:")
    print(claim)

    print("\nVerdict:")
    print(result["verdict"])

    print("\nReason:")
    print(result["reason"])